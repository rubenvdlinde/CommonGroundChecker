/**
 * Generates config/functionalities.yml from the GEMMA ArchiMate model.
 *
 *   npm run --silent taxonomy:gemma -- [--file PATH] [--commit SHA]
 *
 * Without --file it downloads export/GEMMA release.xml from
 * VNG-Realisatie/GEMMA-Archi-repository at --commit (default: master).
 * The model is published under the EUPL; so is this file.
 */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import yaml from "js-yaml";
import { taxonomyFromGemma } from "../src/lib/functionalities/gemma";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const REPOSITORY = "https://github.com/VNG-Realisatie/GEMMA-Archi-repository";

const HEADER = `# The functionality taxonomy of the Common Ground Checker.
#
# Generated by \`npm run taxonomy:gemma\` from the GEMMA ArchiMate model of
# VNG Realisatie, published under the EUPL:
# ${REPOSITORY}, export/GEMMA release.xml.
# Do not edit by hand: regenerate it when GEMMA publishes a new release.
#
# referenceComponents  the GEMMA reference components (referentiecomponenten)
# functionalities      the application services (applicatieservices) they realise
#
# A component names the ids of its functionalities in config/repositories.yml.
`;

async function main(argv: string[]): Promise<number> {
  const option = (name: string) => {
    const index = argv.indexOf(name);
    return index >= 0 ? argv[index + 1] : undefined;
  };
  const commit = option("--commit") ?? null;
  const url = `https://raw.githubusercontent.com/VNG-Realisatie/GEMMA-Archi-repository/${commit ?? "master"}/export/GEMMA%20release.xml`;
  const file = option("--file");
  let xml: string;
  if (file) {
    xml = readFileSync(file, "utf-8");
  } else {
    const response = await fetch(url);
    if (!response.ok) {
      process.stderr.write(`taxonomy:gemma: ${url} answered ${response.status}\n`);
      return 2;
    }
    xml = await response.text();
  }
  const taxonomy = taxonomyFromGemma(xml, { url: REPOSITORY, commit });
  const body = yaml.dump(taxonomy, { lineWidth: -1, noRefs: true, quotingType: '"' });
  writeFileSync(path.join(ROOT, "config/functionalities.yml"), `${HEADER}\n${body}`);
  process.stdout.write(
    `${taxonomy.referenceComponents.length} reference components, ${taxonomy.functionalities.length} functionalities.\n`
  );
  return 0;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main(process.argv.slice(2)).then((code) => process.exit(code));
}
